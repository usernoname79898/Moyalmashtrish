-- 011_crm_appointments.sql
--
-- Adds the missing workshop-operations layer on top of the existing work
-- journal: customers, vehicles, appointments, payment state and status history.
--
-- Durability rules for this file, same as every other migration here:
--   * no DROP TABLE, TRUNCATE or DELETE;
--   * every table/column is created with IF NOT EXISTS;
--   * legacy customer/vehicle data in work_logs is copied, never moved;
--   * existing rows get safe defaults and remain readable by older clients.

CREATE TABLE IF NOT EXISTS customers (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name   TEXT NOT NULL CHECK (length(btrim(full_name)) > 0),
  phone       TEXT NOT NULL DEFAULT '',
  email       TEXT NOT NULL DEFAULT '',
  address     TEXT NOT NULL DEFAULT '',
  notes       TEXT NOT NULL DEFAULT '',
  is_active   INTEGER NOT NULL DEFAULT 1,
  created_at  TEXT NOT NULL DEFAULT app_now(),
  updated_at  TEXT NOT NULL DEFAULT app_now()
);

CREATE TABLE IF NOT EXISTS vehicles (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id   INTEGER REFERENCES customers(id) ON DELETE SET NULL,
  brand         TEXT NOT NULL DEFAULT '',
  model         TEXT NOT NULL DEFAULT '',
  year          INTEGER,
  plate_number  TEXT NOT NULL DEFAULT '',
  vin           TEXT NOT NULL DEFAULT '',
  color         TEXT NOT NULL DEFAULT '',
  notes         TEXT NOT NULL DEFAULT '',
  is_active     INTEGER NOT NULL DEFAULT 1,
  created_at    TEXT NOT NULL DEFAULT app_now(),
  updated_at    TEXT NOT NULL DEFAULT app_now()
);

CREATE TABLE IF NOT EXISTS appointments (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id       INTEGER REFERENCES customers(id) ON DELETE SET NULL,
  vehicle_id        INTEGER REFERENCES vehicles(id) ON DELETE SET NULL,
  customer_name     TEXT NOT NULL DEFAULT '',
  customer_phone    TEXT NOT NULL DEFAULT '',
  car_brand         TEXT NOT NULL DEFAULT '',
  car_model         TEXT NOT NULL DEFAULT '',
  car_number        TEXT NOT NULL DEFAULT '',
  service_type      TEXT NOT NULL DEFAULT '',
  scheduled_date    TEXT NOT NULL DEFAULT '',
  scheduled_time    TEXT NOT NULL DEFAULT '',
  master_id         INTEGER REFERENCES users(id) ON DELETE SET NULL,
  status            TEXT NOT NULL DEFAULT 'Kutilayotgan'
                      CHECK (status IN ('Kutilayotgan', 'Tasdiqlangan', 'Jarayonda', 'Tugallangan', 'Bekor qilingan')),
  notes             TEXT NOT NULL DEFAULT '',
  source            TEXT NOT NULL DEFAULT 'admin',
  work_log_id       INTEGER REFERENCES work_logs(id) ON DELETE SET NULL,
  created_by        INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at        TEXT NOT NULL DEFAULT app_now(),
  updated_at        TEXT NOT NULL DEFAULT app_now()
);

