-- Copy the customer snapshots already present on work_logs into the new table.
-- This is additive: the original text columns are left exactly as they are, so
-- old rows keep working even if a customer is later renamed.
INSERT INTO customers (full_name, phone, created_at, updated_at)
SELECT DISTINCT ON (lower(btrim(w.customer_name)), lower(btrim(w.customer_phone)))
       COALESCE(NULLIF(btrim(w.customer_name), ''), btrim(w.customer_phone)),
       btrim(w.customer_phone), w.created_at, w.updated_at
  FROM work_logs w
 WHERE (btrim(w.customer_name) <> '' OR btrim(w.customer_phone) <> '')
   AND NOT EXISTS (
     SELECT 1 FROM customers c
      WHERE lower(btrim(c.full_name)) = lower(COALESCE(NULLIF(btrim(w.customer_name), ''), btrim(w.customer_phone)))
        AND lower(btrim(c.phone)) = lower(btrim(w.customer_phone))
   )
 ORDER BY lower(btrim(w.customer_name)), lower(btrim(w.customer_phone)), w.created_at;

UPDATE work_logs w
   SET customer_id = c.id
  FROM customers c
 WHERE w.customer_id IS NULL
   AND lower(btrim(c.full_name)) = lower(COALESCE(NULLIF(btrim(w.customer_name), ''), btrim(w.customer_phone)))
   AND lower(btrim(c.phone)) = lower(btrim(w.customer_phone))
   AND (btrim(w.customer_name) <> '' OR btrim(w.customer_phone) <> '');

-- Link the vehicles those jobs already describe. A vehicle belongs to the
-- customer the job was filed for; jobs with no customer keep their text fields
-- and can be linked from the UI later.
INSERT INTO vehicles (customer_id, brand, model, plate_number, created_at, updated_at)
SELECT
       w.customer_id,
       min(btrim(w.car_brand)), min(btrim(w.car_model)), min(btrim(w.car_number)),
       min(w.created_at), max(w.updated_at)
  FROM work_logs w
 WHERE w.customer_id IS NOT NULL
   AND (btrim(w.car_brand) <> '' OR btrim(w.car_model) <> '' OR btrim(w.car_number) <> '')
   AND NOT EXISTS (
     SELECT 1 FROM vehicles v
      WHERE v.customer_id = w.customer_id
        AND lower(btrim(v.brand)) = lower(btrim(w.car_brand))
        AND lower(btrim(v.model)) = lower(btrim(w.car_model))
        AND lower(btrim(v.plate_number)) = lower(btrim(w.car_number))
   )
 GROUP BY w.customer_id, lower(btrim(w.car_brand)), lower(btrim(w.car_model)), lower(btrim(w.car_number))
 ORDER BY w.customer_id, lower(btrim(w.car_brand)), lower(btrim(w.car_model)), lower(btrim(w.car_number)), min(w.created_at);

UPDATE work_logs w
   SET vehicle_id = v.id
  FROM vehicles v
 WHERE w.vehicle_id IS NULL
   AND v.customer_id = w.customer_id
   AND lower(btrim(v.brand)) = lower(btrim(w.car_brand))
   AND lower(btrim(v.model)) = lower(btrim(w.car_model))
   AND lower(btrim(v.plate_number)) = lower(btrim(w.car_number));
